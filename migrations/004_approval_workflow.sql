-- 004: make the approval tables match the app's one-step, per-table approval workflow.
-- The app needs a setup row to name the table it governs and to carry e-signature / lock flags,
-- and each workflow event to record action, statuses, signer, e-signature hash and IP (21 CFR Part 11).
-- Multi-step / reminder columns stay but become optional. Idempotent.

-- Setup: which table, and how approval behaves. Approver role is the existing pas_appr_role_type.
ALTER TABLE phc_approval_setup_t ADD COLUMN IF NOT EXISTS pas_table_name varchar(120);
ALTER TABLE phc_approval_setup_t ADD COLUMN IF NOT EXISTS pas_require_esig boolean NOT NULL DEFAULT true;
ALTER TABLE phc_approval_setup_t ADD COLUMN IF NOT EXISTS pas_auto_lock_on_submit boolean NOT NULL DEFAULT true;
ALTER TABLE phc_approval_setup_t ALTER COLUMN pas_appr_seq SET DEFAULT 1;
ALTER TABLE phc_approval_setup_t ALTER COLUMN pas_event_freq_type DROP NOT NULL;
ALTER TABLE phc_approval_setup_t ALTER COLUMN pas_event_freq DROP NOT NULL;
ALTER TABLE phc_approval_setup_t ALTER COLUMN pas_event_waiting_min DROP NOT NULL;
ALTER TABLE phc_approval_setup_t ALTER COLUMN pas_start_date SET DEFAULT CURRENT_DATE;

-- Events: what happened, who signed, and the signature hash.
ALTER TABLE phc_approval_events_t ADD COLUMN IF NOT EXISTS pae_action varchar(20);
ALTER TABLE phc_approval_events_t ADD COLUMN IF NOT EXISTS pae_from_status varchar(20);
ALTER TABLE phc_approval_events_t ADD COLUMN IF NOT EXISTS pae_to_status varchar(20);
ALTER TABLE phc_approval_events_t ADD COLUMN IF NOT EXISTS pae_user_id bigint;
ALTER TABLE phc_approval_events_t ADD COLUMN IF NOT EXISTS pae_username varchar(100);
ALTER TABLE phc_approval_events_t ADD COLUMN IF NOT EXISTS pae_user_role varchar(60);
ALTER TABLE phc_approval_events_t ADD COLUMN IF NOT EXISTS pae_esig_hash varchar(64);
ALTER TABLE phc_approval_events_t ADD COLUMN IF NOT EXISTS pae_client_ip varchar(64);
ALTER TABLE phc_approval_events_t ALTER COLUMN pae_appr_emp_no DROP NOT NULL;
ALTER TABLE phc_approval_events_t ALTER COLUMN pae_event_freq_type DROP NOT NULL;
ALTER TABLE phc_approval_events_t ALTER COLUMN pae_event_freq DROP NOT NULL;
ALTER TABLE phc_approval_events_t ALTER COLUMN pae_event_waiting_min DROP NOT NULL;
ALTER TABLE phc_approval_events_t ALTER COLUMN pae_event_status DROP NOT NULL;
ALTER TABLE phc_approval_events_t ALTER COLUMN pae_event_start SET DEFAULT CURRENT_DATE;
ALTER TABLE phc_approval_events_t ALTER COLUMN pae_event_end DROP NOT NULL;
CREATE INDEX IF NOT EXISTS phc_approval_events_record_idx ON phc_approval_events_t (pae_event_table, pae_event_table_pk_id);

-- Both ids had no default, so nothing could insert a row.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'phc_approval_setup_t'
               AND column_name = 'pas_appr_setup_id' AND column_default IS NULL AND is_identity = 'NO') THEN
        ALTER TABLE phc_approval_setup_t ALTER COLUMN pas_appr_setup_id ADD GENERATED BY DEFAULT AS IDENTITY;
        PERFORM setval(pg_get_serial_sequence('phc_approval_setup_t', 'pas_appr_setup_id'),
                       COALESCE((SELECT MAX(pas_appr_setup_id) FROM phc_approval_setup_t), 0) + 1, false);
    END IF;
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'phc_approval_events_t'
               AND column_name = 'pae_appr_event_id' AND column_default IS NULL AND is_identity = 'NO') THEN
        ALTER TABLE phc_approval_events_t ALTER COLUMN pae_appr_event_id ADD GENERATED BY DEFAULT AS IDENTITY;
        PERFORM setval(pg_get_serial_sequence('phc_approval_events_t', 'pae_appr_event_id'),
                       COALESCE((SELECT MAX(pae_appr_event_id) FROM phc_approval_events_t), 0) + 1, false);
    END IF;
END $$;
